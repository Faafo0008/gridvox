#!/usr/bin/env python3
"""Embed TTF files as base64 string literals (fast to compile, decoded once at startup)."""
import os, sys, base64, textwrap
src, out = sys.argv[1], sys.argv[2]
names = {
    "Michroma-Regular.ttf": "michroma",
    "ShareTechMono-Regular.ttf": "shareTechMono",
    "ChakraPetch-Regular.ttf": "chakraRegular",
    "ChakraPetch-SemiBold.ttf": "chakraSemiBold",
}
files = [f for f in sorted(os.listdir(src)) if f.endswith('.ttf') and f in names]
with open(out, 'w') as f:
    f.write("// Auto-generated by Tools/embed_fonts.py - do not edit.\n")
    f.write('#include "FontData.h"\n\nnamespace GridVoxFonts\n{\n')
    for fn in files:
        b64 = base64.b64encode(open(os.path.join(src, fn), 'rb').read()).decode('ascii')
        ident = names[fn]
        f.write(f"const char* {ident}Base64 =\n")
        for line in textwrap.wrap(b64, 200):
            f.write(f'    "{line}"\n')
        f.write(";\n\n")
    f.write("const char* michromaB64 = michromaBase64;\n")
    f.write("} // namespace GridVoxFonts\n")
print("wrote", out, len(files), "fonts")
